"""Rebuild knowledge/INDEX.md from note frontmatter.
Usage: python skills/knowledge-base/scripts/knowledge_index.py [path/to/knowledge]
Default knowledge root: the brimpa-skills repo layout (../../../knowledge relative to this script).
"""
import pathlib, re, sys

root = pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[3] / "knowledge"
if not root.is_dir():
    sys.exit(f"knowledge folder not found: {root} (pass its path as the first argument)")

rows = []
for md in sorted(root.rglob("*.md")):
    if md.name in ("README.md", "INDEX.md") or "inbox" in md.parts:
        continue
    text = md.read_text(encoding="utf-8", errors="ignore")
    m = re.match(r"^---\r?\n(.*?)\r?\n---", text, re.S)
    if not m:
        print(f"skip (no frontmatter): {md.relative_to(root)}", file=sys.stderr)
        continue
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    rel = md.relative_to(root).as_posix()
    rows.append((fm.get("topic", ""), fm.get("title", md.stem), rel, fm.get("tags", ""), fm.get("confidence", ""), fm.get("date", "")))

rows.sort()
out = ["# Knowledge index", "", "Generated by skills/knowledge-base/scripts/knowledge_index.py. One line per note; open the file for the full note.", "",
       "| Topic | Title | File | Tags | Confidence | Date |", "|---|---|---|---|---|---|"]
for topic, title, rel, tags, conf, date in rows:
    out.append(f"| {topic} | {title} | [{rel}]({rel}) | {tags} | {conf} | {date} |")
(root / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"indexed {len(rows)} notes -> {root / 'INDEX.md'}")
